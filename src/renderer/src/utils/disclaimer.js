// ============================================================
// 确认状态读写（ack）
// ============================================================

function defaultStore() {
  try {
    return typeof globalThis !== 'undefined' ? globalThis.localStorage : null;
  } catch {
    return null;
  }
}

/** 是否已确认**当前版本**的条款 */
export function hasAckedDisclaimer(store = defaultStore()) {
  if (!store || typeof store.getItem !== 'function') return false;
  try {
    return !!store.getItem(DISCLAIMER_ACK_KEY);
  } catch {
    return false;
  }
}

/** 返回确认时间（ISO 字符串）；未确认或时间戳损坏 → null */
export function ackedDisclaimerAt(store = defaultStore()) {
  if (!store || typeof store.getItem !== 'function') return null;
  try {
    const raw = store.getItem(DISCLAIMER_ACK_KEY);
    if (!raw) return null;
    const t = new Date(raw);
    return Number.isNaN(t.getTime()) ? null : raw;
  } catch {
    return null;
  }
}

/** 记下确认（写入 ISO 时间戳）。写入失败返回 false —— 调用方据此提示「本次会话内有效」 */
export function ackDisclaimer(store = defaultStore(), at = new Date()) {
  if (!store || typeof store.setItem !== 'function') return false;
  try {
    store.setItem(DISCLAIMER_ACK_KEY, at.toISOString());
    return true;
  } catch {
    return false;
  }
}

/** 清除确认记录（仅用于测试/重置；产品 UI 不暴露此入口） */
export function clearDisclaimerAck(store = defaultStore()) {
  if (!store || typeof store.removeItem !== 'function') return false;
  try {
    store.removeItem(DISCLAIMER_ACK_KEY);
    return true;
  } catch {
    return false;
  }
}

