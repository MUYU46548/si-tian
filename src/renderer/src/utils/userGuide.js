// utils/userGuide.js — 应用内「使用手册」的**唯一事实源**（纯数据 + 一个搜索函数）
//
// 为什么单独一个文件：
//   ① 手册文案与组件解耦（改字不动 .vue）——与 `utils/disclaimer.js` 同一套做法；
//   ② 能被 Node 单测直接读（`test_user_guide.js` 守「章节骨架 / 关键词 / 出处」在场），
//      也能被将来别的入口（引导、状态栏提示、命令行 `--help`）复用同一份文案。
//
// 它要解决的**具体问题**（2026-10-11，暮雨原话）：
//   「顺便告诉我我应该怎么测试，如何真正用起来？右上角问号点进去是关于，司天内没有教程。
//     我记得以前有（虽然很简陋没什么用）。」
//   仓库里一直有 `docs/SCENARIO_GUIDE.md`（比这里细得多），但**用户只有 exe，看不到仓库**。
//   所以这里的判据不是"写没写"，而是「**他照着能不能做完一件事**」：
//   每节都要有可点的按钮名与可敲的键，并且不许出现仓库里才有的概念（commit / 测试用例号）。
//
// 诚实边界：`cite` 只用于维护者回溯（用户界面上以小字显示），不是"官方文档"；
// 打不开的路径、做不到的事**不要写进来** —— 手册写错比没有手册更坏。

