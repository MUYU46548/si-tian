/** 供测试与 UI 显示：章节数 / 关键词总数 */
export function guideStats() {
  return {
    version: GUIDE_VERSION,
    sections: GUIDE_SECTIONS.length,
    keywords: GUIDE_SECTIONS.reduce((n, s) => n + (s.keywords || []).length, 0),
  };
}

/**
 * 搜索章节：标题 / 关键词 / 正文全部参与匹配（大小写不敏感）。
 * 空查询返回全部（保持原顺序 —— 手册的章节顺序本身就是推荐阅读顺序）。
 * @param {string} q
 * @returns {Array} 章节子集
 */
export function searchGuide(q) {
  const term = String(q || '').trim().toLowerCase();
  if (!term) return GUIDE_SECTIONS;
  const terms = term.split(/\s+/).filter(Boolean);
  return GUIDE_SECTIONS.filter((s) => {
    const hay = [
      s.title,
      ...(s.keywords || []),
      ...(s.blocks || []).map((b) => (Array.isArray(b.v) ? b.v.map((x) => (Array.isArray(x) ? x.join(' ') : x)).join(' ') : b.v)),
    ].join(' ').toLowerCase();
    return terms.every((t) => hay.includes(t));
  });
}
